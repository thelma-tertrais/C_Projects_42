#include "libft.h"

int	ft_atoi(const char *str)
{
	int		i;
	int		negatif;
	int		nb;

	i = 0;
	nb = 0;
	negatif = 1;
	while (str[i] == 32 || (str[i] >= 9 && str[i] <= 13))
		i++;
	if (str[i] == '-' || str[i] == '+')
	{
		if (str[i] == '-')
			negatif = negatif * (-1);
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		nb = nb * 10 + str[i] - '0';
		i++;
	}
	return (nb * negatif);
}
